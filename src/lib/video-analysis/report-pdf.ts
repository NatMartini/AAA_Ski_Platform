import { readFile } from "node:fs/promises";
import path from "node:path";
import { PDFDocument, rgb, type PDFFont, type PDFPage, type RGB } from "pdf-lib";
import fontkit from "@pdf-lib/fontkit";
import { wrap } from "../waiver/render";
import { getFreeSkiActionOption, FREESKI_CURRENT_LEVELS, parseFreeSkiActionId } from "../freeski/actions";
import { metricStanding } from "../freeski/metric-insight";
import { scorecardSchema, type Scorecard, type Teaching } from "../freeski/scorecard";
import { faultsFor, GUIDE_DRILLS } from "../freeski/technique-faults";
import { formatTorontoDateTime } from "../time";

/**
 * The analysis report as a PDF to download and keep (owner's decision, 2026-11-07): videos are kept for one ski
 * season, the report for good. It carries the conclusion, every measurement, the movement explanations with the
 * guide's fixes and drills, and FreeSki's written explanation when it could be read.
 */

const FONT_PATH = path.resolve("assets/fonts/NotoSansSC-Regular.ttf");
let fontCache: Buffer | null = null;
const fontBytes = async () => fontCache ??= await readFile(FONT_PATH);

const PAGE = { width: 595.28, height: 841.89 };
const MARGIN = 50;
const WIDTH = PAGE.width - MARGIN * 2;
const INK = rgb(0.07, 0.13, 0.18), MUTED = rgb(0.38, 0.44, 0.5), ACCENT = rgb(0.1, 0.37, 0.8), GOOD = rgb(0.1, 0.55, 0.35),
  WORK = rgb(0.72, 0.42, 0.04), RULE = rgb(0.84, 0.87, 0.9);

export type ReportPdfInput = {
  zh: boolean;
  actionId: string;
  caption: string | null;
  submittedAt: Date;
  finishedAt: Date | null;
  /** The job's stored result: its scorecard is read from it. */
  result: unknown;
  teaching: Teaching | null;
};

/** "CSIA 2 级 · 小回转 · 目前 CSIA 1 级", as the site names an analysis. */
export function analysisTitle(actionId: string, zh: boolean) {
  const selection = parseFreeSkiActionId(actionId);
  const action = getFreeSkiActionOption(actionId);
  const level = FREESKI_CURRENT_LEVELS.find(candidate => candidate.id === selection?.currentLevel);
  if (!action) return zh ? "滑雪动作分析" : "Skiing analysis";
  return [action.pathType === "certification" ? (zh ? action.groupZh : action.groupEn) : null, zh ? action.labelZh : action.labelEn,
    level ? level.id === "none" ? (zh ? level.labelZh : level.labelEn) : zh ? `目前 ${level.labelZh}` : `Currently ${level.labelEn}` : null]
    .filter(Boolean).join(" · ");
}

class Writer {
  page!: PDFPage;
  y = 0;
  pages = 0;
  constructor(private doc: PDFDocument, private font: PDFFont, private footer: string) { this.newPage(); }
  newPage() {
    this.page = this.doc.addPage([PAGE.width, PAGE.height]);
    this.y = PAGE.height - MARGIN;
    this.pages++;
    this.page.drawText(`${this.footer} · ${this.pages}`, { x: MARGIN, y: MARGIN / 2, size: 7.5, font: this.font, color: MUTED });
  }
  ensure(needed: number) { if (this.y - needed < MARGIN) this.newPage(); }
  text(value: string, { size = 10, color = INK, indent = 0, gap = 1.5 }: { size?: number; color?: RGB; indent?: number; gap?: number } = {}) {
    for (const line of wrap(value, this.font, size, WIDTH - indent)) {
      this.ensure(size * gap);
      this.y -= size * gap;
      this.page.drawText(line, { x: MARGIN + indent, y: this.y, size, font: this.font, color });
    }
  }
  heading(value: string) {
    this.ensure(40);
    this.y -= 10;
    this.text(value, { size: 13, color: ACCENT, gap: 1.6 });
    this.y -= 3;
    this.page.drawLine({ start: { x: MARGIN, y: this.y }, end: { x: PAGE.width - MARGIN, y: this.y }, thickness: .6, color: RULE });
    this.y -= 4;
  }
  /** A label and a value on one line, the value at the right edge. */
  row(label: string, value: string, color: RGB) {
    const size = 9.5;
    this.ensure(size * 1.6);
    this.y -= size * 1.6;
    this.page.drawText(wrap(label, this.font, size, WIDTH - 130)[0] ?? "", { x: MARGIN + 6, y: this.y, size, font: this.font, color: INK });
    this.page.drawText(value, { x: PAGE.width - MARGIN - this.font.widthOfTextAtSize(value, size), y: this.y, size, font: this.font, color });
  }
  gap(points: number) { this.y -= points; }
}

export async function renderAnalysisReportPdf(input: ReportPdfInput): Promise<Uint8Array> {
  const { zh } = input;
  const card: Scorecard | null = (() => {
    const raw = input.result && typeof input.result === "object" ? (input.result as Record<string, unknown>).scorecard : null;
    return scorecardSchema.safeParse(raw).data ?? null;
  })();
  const doc = await PDFDocument.create();
  doc.registerFontkit(fontkit);
  const font = await doc.embedFont(await fontBytes(), { subset: true });
  const title = analysisTitle(input.actionId, zh);
  doc.setTitle(`FreeSki · ${title}`);
  doc.setCreator("AAA Ski Platform");
  const w = new Writer(doc, font, zh ? "AAA 双板 · FreeSki 自动生成，教练确认前仅供参考" : "AAA Ski · Generated by FreeSki; a guide until a coach confirms it");

  w.text(zh ? "FreeSki 视频分析报告" : "FreeSki video analysis report", { size: 18, gap: 1.4 });
  w.gap(4);
  w.text(title, { size: 13, color: ACCENT });
  w.text([input.caption, `${zh ? "提交" : "Submitted"} ${formatTorontoDateTime(input.submittedAt, zh ? "zh" : "en")}`,
    input.finishedAt ? `${zh ? "完成" : "Finished"} ${formatTorontoDateTime(input.finishedAt, zh ? "zh" : "en")}` : null]
    .filter(Boolean).join(" · "), { size: 9, color: MUTED });

  // The conclusion: the written explanation's when there is one, else the measurements' own.
  w.heading(zh ? "结论" : "Summary");
  const teaching = input.teaching;
  if (teaching) {
    w.text(zh ? teaching.summary_zh : teaching.summary_en);
    for (const item of teaching.strengths) w.text(`${zh ? "做得好：" : "Doing well: "}${zh ? item.text_zh : item.text_en}`, { color: GOOD, indent: 6 });
    for (const item of teaching.improvements) w.text(`${zh ? "要改进：" : "To work on: "}${zh ? item.text_zh : item.text_en}`, { color: WORK, indent: 6 });
  } else if (card) {
    const scored = card.metrics.filter(metric => metric.score !== null);
    const good = scored.filter(metric => metricStanding(metric) === "good").sort((a, b) => b.score! - a.score!).slice(0, 2);
    const work = scored.filter(metric => metricStanding(metric) === "work").sort((a, b) => a.score! - b.score!).slice(0, 2);
    for (const metric of good) w.text(`${zh ? "做得好：" : "Doing well: "}${zh ? metric.label_zh : metric.label_en} ${Math.round(metric.score!)}`, { color: GOOD });
    for (const metric of work) w.text(`${zh ? "最该练：" : "Work on first: "}${zh ? metric.label_zh : metric.label_en} ${Math.round(metric.score!)}`, { color: WORK });
    if (!good.length && !work.length) w.text(zh ? "这次的数据没有明显的长处或短板。" : "No clear strength or weakness in this run's measurements.");
  } else {
    w.text(zh ? "这次没有评分卡，报告里只有分析时间。" : "This analysis has no scorecard; the report only records when it ran.");
  }

  if (card) {
    w.heading(zh ? `各项数据 · ${card.metrics.length} 项` : `Measurements · ${card.metrics.length}`);
    const names = { good: zh ? "达标" : "in range", work: zh ? "待改进" : "to work on", estimated: zh ? "估算" : "estimate", none: zh ? "未测到" : "not measured" };
    for (const metric of card.metrics) {
      const standing = metricStanding(metric);
      w.row(zh ? metric.label_zh : metric.label_en, `${metric.score === null ? "—" : Math.round(metric.score)} · ${names[standing]}`,
        standing === "good" ? GOOD : standing === "work" ? WORK : MUTED);
    }

    const faults = faultsFor(card);
    if (faults.length) {
      w.heading(zh ? "动作讲解" : "Your movements explained");
      faults.forEach(({ fault }, index) => {
        w.ensure(60);
        w.text(`${index + 1}. ${zh ? fault.zh : fault.en}`, { size: 11.5, gap: 1.7 });
        w.text(`${zh ? "视频里看什么：" : "What to look for: "}${zh ? fault.seeZh : fault.seeEn}`, { indent: 10, size: 9.5 });
        w.text(`${zh ? "为什么：" : "Why: "}${zh ? fault.whyZh : fault.whyEn}`, { indent: 10, size: 9.5 });
        w.text(`${zh ? "怎么改：" : "What to do: "}${zh ? fault.fixZh : fault.fixEn}（CSIA ${fault.source}）`, { indent: 10, size: 9.5 });
        for (const id of fault.drills) {
          const drill = GUIDE_DRILLS[id];
          w.text(`${zh ? "练习" : "Drill"}：${zh ? drill.zh : drill.en}——${zh ? drill.purposeZh : drill.purposeEn}`, { indent: 18, size: 9, color: MUTED });
        }
        w.gap(4);
      });
    }
  }

  if (teaching?.drills.length) {
    w.heading(zh ? "怎么练" : "How to practise");
    for (const drill of teaching.drills) {
      w.text(zh ? drill.name_zh : drill.name_en, { size: 10.5 });
      w.text(zh ? drill.why_zh : drill.why_en, { indent: 10, size: 9.5, color: MUTED });
    }
  }
  if (teaching && (zh ? teaching.limitations_zh : teaching.limitations_en).length) {
    w.heading(zh ? "需要注意" : "Limits of this analysis");
    for (const note of zh ? teaching.limitations_zh : teaching.limitations_en) w.text(note, { size: 9, color: MUTED });
  }
  w.gap(10);
  w.text(zh ? "视频只保存一个雪季（到 5 月 31 日）；这份报告可以一直保留。" : "Videos are kept for one ski season (until May 31); this report is yours to keep.", { size: 8.5, color: MUTED });
  return doc.save();
}
